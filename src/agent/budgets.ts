/**
 * 上下文预算的唯一定义点（WP6 轻量收口）。
 *
 * 这五个预算共同决定「一轮对话里，模型能看见多少东西」，彼此是此消彼长的关系：
 * 单次输出放宽一点、历史就得缩一点，否则思考型模型被上下文拖到超时或截断。
 * 以前它们散在五个文件里互不知情，调一个等于盲调——现在集中在这里，
 * 各模块只申请配额、不自定义数值。
 *
 * 改这里之前先看一眼全局：任何一个值放大，都要想想另外四个装不装得下。
 */

// ── 单次输出：一个工具结果最多往上下文里塞多少字符 ──────────────────────────
/** 单次工具输出的硬上限，防止一次读取把上下文撑爆（超过会截断或外溢） */
export const MAX_OUTPUT_CHARS = 20_000;

// ── 批量读取：read_files 一次拿多少 ─────────────────────────────────────────
/** 一次最多读几个文件（再多的分批调用） */
export const BATCH_MAX_FILES = 20;
/** 批量模式下单篇文件截到的字符数 */
export const BATCH_PER_FILE_CHARS = 3000;
/** 批量模式下整批总共的字符预算 */
export const BATCH_TOTAL_CHARS = 12000;

// ── 内联 vs 外溢：多大的结果留在上下文，多大的落盘 ──────────────────────────
/** 超过这个长度就外溢到磁盘，上下文里只留「开头 + 落点」 */
export const MAX_INLINE_CHARS = 4000;
/** 外溢后仍直接放进上下文的开头长度 */
export const SPILL_HEAD_CHARS = 1200;

// ── 跨轮历史：上一轮对话带进来多少 ─────────────────────────────────────────
/** 历史总共允许多少字符（不含本轮用户输入） */
export const HISTORY_BUDGET = 4000;
/** 单条超过这个长度就截断：留头留尾，中间标省略 */
export const HISTORY_TURN_CAP = 1200;

// ── 整体门槛：整个上下文多大时开始瘦身（prune） ────────────────────────────
/**
 * 上下文里超过这个字符数才值得动手（约 5.3k token）。
 *
 * 原来是 24000。翻 63 个真机存档量了一下：中位数 4641 字符，真实闲聊/小任务根本到不了
 * 24000——也就是说这个阈值在真实使用里等于「永不触发」，只有自检能碰它。
 * 而 24000 这个数字本来是从「一个 9 步任务烧了 92405 prompt token」那次反推的，
 * 那次的上下文峰值是 31277 字符，早就越过 16000 了。
 */
export const CONTEXT_CHARS_GATE = 16000;
/** 消息条数超过这个也动手：短消息多到这个份上，结构本身就是负担 */
export const PRUNE_MAX_MESSAGES = 48;
